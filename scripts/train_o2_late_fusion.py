def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def sha256_file(path: Path, chunk_size: int = 8 * 1024 * 1024) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        while chunk := stream.read(chunk_size):
            digest.update(chunk)
    return digest.hexdigest()


def causal_moving_average(values: np.ndarray, width: int) -> np.ndarray:
    """Apply a causal moving average without shifting the waveform."""
    cumulative = np.cumsum(values, axis=1, dtype=np.float32)
    result = np.empty_like(values, dtype=np.float32)
    prefix_lengths = np.arange(1, width, dtype=np.float32)
    if width > 1:
        result[:, : width - 1] = cumulative[:, : width - 1] / prefix_lengths[None, :]
    previous = np.concatenate(
        (
            np.zeros((values.shape[0], 1), dtype=np.float32),
            cumulative[:, :-width],
        ),
        axis=1,
    )
    result[:, width - 1 :] = (
        cumulative[:, width - 1 :] - previous
    ) / float(width)
    return result


def interpolated_t10(smoothed_charge: np.ndarray) -> tuple[np.ndarray, int]:
    """Return fractional t10 crossings and the count of deterministic fallbacks.

    The pulse peak is selected from the same smoothed, baseline-subtracted charge
    representation used for the crossing.  The crossing is linearly interpolated
    between adjacent samples, making the subsequent window alignment deterministic.
    A selected low-energy/no-pulse candidate can have a non-positive smoothed peak;
    in that case the charge window is deterministically padded from sample 1000 and
    the fallback is recorded in run metadata rather than silently dropping the event.
    """
    peak_indices = (
        np.argmax(
            smoothed_charge[:, T10_SEARCH_START:T10_SEARCH_STOP],
            axis=1,
        )
        + T10_SEARCH_START
    )
    peak_values = smoothed_charge[
        np.arange(smoothed_charge.shape[0]), peak_indices
    ]
    valid = peak_values > 0.0
    fallback_count = int(np.count_nonzero(~valid))
    positions = np.full(
        smoothed_charge.shape[0], float(T10_SEARCH_START), dtype=np.float32
    )
    if not np.any(valid):
        return positions, fallback_count
    search = smoothed_charge[:, T10_SEARCH_START:T10_SEARCH_STOP]
    search_offsets = np.arange(search.shape[1], dtype=np.int64)
    thresholds = 0.1 * peak_values
    before_peak = search_offsets[None, :] <= (
        peak_indices - T10_SEARCH_START
    )[:, None]
    crossed = (search >= thresholds[:, None]) & before_peak & valid[:, None]
    if np.any(valid & ~np.any(crossed, axis=1)):
        index = int(np.flatnonzero(valid & ~np.any(crossed, axis=1))[0])
        raise ValueError(
            "No t10 crossing found in the physical search interval; "
            f"event batch index={index}, peak_index={peak_indices[index]}"
        )
    crossing = np.argmax(crossed, axis=1) + T10_SEARCH_START
    interpolated = valid & (crossing > T10_SEARCH_START)
    indices = np.flatnonzero(interpolated)
    if indices.size:
        crossing_indices = crossing[indices]
        before = smoothed_charge[indices, crossing_indices - 1]
        after = smoothed_charge[indices, crossing_indices]
        denominator = after - before
        fraction = np.divide(
            thresholds[indices] - before,
            denominator,
            out=np.zeros_like(before, dtype=np.float32),
            where=denominator != 0.0,
        )
        positions[indices] = (
            crossing_indices.astype(np.float32)
            - 1.0
            + np.clip(fraction, 0.0, 1.0)
        )
    return positions, fallback_count


def extract_o2_features(
    waveforms: np.ndarray,
    shaped_energy_unit: np.ndarray,
) -> tuple[np.ndarray, np.ndarray, int]:
    """Extract normalized charge and current branch inputs for one batch."""
    waveforms = np.asarray(waveforms, dtype=np.float32)
    shaped_energy_unit = np.asarray(shaped_energy_unit, dtype=np.float32)
    if waveforms.ndim != 2 or waveforms.shape[1] != 4500:
        raise ValueError(f"Expected (N, 4500) waveforms, got {waveforms.shape}")
    if not np.all(np.isfinite(waveforms)):
        raise ValueError("Non-finite waveform sample encountered")
    if not np.all(np.isfinite(shaped_energy_unit)) or np.any(shaped_energy_unit <= 0.0):
        raise ValueError("Frozen shaped_energy_unit must be finite and positive")

    baseline = np.median(waveforms[:, :BASELINE_STOP], axis=1).astype(np.float32)
    charge = baseline[:, None] - waveforms
    smoothed_charge = causal_moving_average(charge, MOVING_AVERAGE_WIDTH)
    t10, t10_fallback_count = interpolated_t10(smoothed_charge)

    charge_offsets = np.arange(-CHARGE_PRE_SAMPLES, CHARGE_POST_SAMPLES, dtype=np.float32)
    sample_positions = t10[:, None] + charge_offsets[None, :]
    if sample_positions.min() < 0.0 or sample_positions.max() > waveforms.shape[1] - 1:
        raise ValueError("Charge window out of bounds")
    left_indices = np.floor(sample_positions).astype(np.int64)
    right_indices = np.minimum(left_indices + 1, waveforms.shape[1] - 1)
    fraction = sample_positions - left_indices
    event_indices = np.arange(waveforms.shape[0])[:, None]
    left_values = smoothed_charge[event_indices, left_indices]
    right_values = smoothed_charge[event_indices, right_indices]
    charge_branch = (
        left_values + fraction * (right_values - left_values)
    ).astype(np.float32)

    current = np.gradient(charge, SAMPLE_PERIOD_NS, axis=1).astype(np.float32)
    current_peak = (
        np.argmax(
            current[:, CURRENT_SEARCH_START:CURRENT_SEARCH_STOP],
            axis=1,
        )
        + CURRENT_SEARCH_START
    )
    current_offsets = np.arange(
        -CURRENT_HALF_WIDTH,
        CURRENT_HALF_WIDTH + 1,
        dtype=np.int64,
    )
    current_indices = current_peak[:, None] + current_offsets[None, :]
    if current_indices.min() < 0 or current_indices.max() >= waveforms.shape[1]:
        raise ValueError("Current window out of bounds")
    current_branch = current[
        np.arange(waveforms.shape[0])[:, None],
        current_indices,
    ].astype(np.float32)

    # The positive shaped-energy quantity is the frozen trapezoid normalization.
    # Do not use abs(): a non-positive value indicates a reconstruction failure.
    scale = shaped_energy_unit[:, None]
    charge_branch /= scale
    current_branch /= scale
    if not np.all(np.isfinite(charge_branch)) or not np.all(np.isfinite(current_branch)):
        raise ValueError("Non-finite O2 feature generated")
    return charge_branch, current_branch, t10_fallback_count


def read_partition_events(
    csv_path: Path,
    max_events: int | None = None,
) -> list[EventReference]:
    """Expand each positive/negative matched pair into event-level records."""
    records: list[EventReference] = []
    with csv_path.open(newline="", encoding="utf-8") as stream:
        for pair in csv.DictReader(stream):
            records.append(
                EventReference(
                    hdf5_path=pair["positive_hdf5"],
                    row=int(pair["positive_row"]),
                    label=int(pair["positive_label"]),
                    weight=float(pair["source_weight"]),
                    peak_id=pair["peak_id"],
                )
            )
            records.append(
                EventReference(
                    hdf5_path=pair["negative_hdf5"],
                    row=int(pair["negative_row"]),
                    label=int(pair["negative_label"]),
                    weight=float(pair["source_weight"]),
                    peak_id=pair["peak_id"],
                )
            )
            if max_events is not None and len(records) >= max_events:
                break
    if not records:
        raise ValueError(f"No events found in {csv_path}")
    if max_events is not None:
        records = records[:max_events]
    labels = {record.label for record in records}
    if labels != {0, 1}:
        raise ValueError(f"Expected both labels in {csv_path}; found {labels}")
    return records


def build_partition_features(
    csv_path: Path,
    max_events: int | None = None,
    event_store_dir: Path | None = None,
) -> PartitionData:
    """Read only referenced HDF5 rows and construct the event-level features."""
    records = read_partition_events(csv_path, max_events=max_events)
    if event_store_dir is not None:
        return build_partition_features_from_event_store(
            csv_path,
            records,
            event_store_dir,
        )

    charge = np.empty((len(records), CHARGE_LENGTH), dtype=np.float32)
    current = np.empty((len(records), CURRENT_LENGTH), dtype=np.float32)
    labels = np.asarray([record.label for record in records], dtype=np.float32)
    weights = np.asarray([record.weight for record in records], dtype=np.float32)
    peak_ids = np.asarray([record.peak_id for record in records], dtype="U64")
    t10_fallback_count = 0

    grouped: dict[str, list[tuple[int, int]]] = defaultdict(list)
    for destination, record in enumerate(records):
        grouped[record.hdf5_path].append((destination, record.row))

    for relative_path, references in sorted(grouped.items()):
        hdf5_path = PROJECT_ROOT / relative_path
        if not hdf5_path.is_file():
            raise FileNotFoundError(hdf5_path)
        with h5py.File(hdf5_path, "r") as handle:
            waveform_dataset = handle["waveform"]
            energy_dataset = handle["shaped_energy_unit"]
            for start in range(0, len(references), FEATURE_CHUNK_SIZE):
                chunk = references[start : start + FEATURE_CHUNK_SIZE]
                destinations = np.asarray([item[0] for item in chunk], dtype=np.int64)
                rows = np.asarray([item[1] for item in chunk], dtype=np.int64)
                order = np.argsort(rows)
                sorted_rows = rows[order]
                waveforms = waveform_dataset[sorted_rows]
                shaped = energy_dataset[sorted_rows]
                (
                    chunk_charge,
                    chunk_current,
                    chunk_fallback_count,
                ) = extract_o2_features(waveforms, shaped)
                charge[destinations[order]] = chunk_charge
                current[destinations[order]] = chunk_current
                t10_fallback_count += chunk_fallback_count

    return PartitionData(
        charge,
        current,
        labels,
        weights,
        peak_ids,
        t10_fallback_count,
    )


def build_partition_features_from_event_store(
    csv_path: Path,
    records: list[EventReference],
    event_store_dir: Path,
) -> PartitionData:
    """Build features from a consolidated partition store instead of source files."""
    partition = csv_path.stem.removeprefix("label_pairs_")
    store_path = event_store_dir / f"{partition}_events.h5"
    lookup_path = event_store_dir / f"event_lookup_{partition}.csv"
    for path in (store_path, lookup_path):
        if not path.is_file():
            raise FileNotFoundError(path)
    required_keys = {(record.hdf5_path, record.row) for record in records}
    lookup: dict[tuple[str, int], int] = {}
    with lookup_path.open(newline="", encoding="utf-8") as stream:
        for row in csv.DictReader(stream):
            key = (row["source_hdf5"], int(row["source_row"]))
            if key in required_keys:
                lookup[key] = int(row["store_index"])
    missing = required_keys - set(lookup)
    if missing:
        example = next(iter(missing))
        raise KeyError(
            f"Event store is missing {len(missing)} referenced events; example={example}"
        )

    charge = np.empty((len(records), CHARGE_LENGTH), dtype=np.float32)
    current = np.empty((len(records), CURRENT_LENGTH), dtype=np.float32)
    labels = np.asarray([record.label for record in records], dtype=np.float32)
    weights = np.asarray([record.weight for record in records], dtype=np.float32)
    peak_ids = np.asarray([record.peak_id for record in records], dtype="U64")
    store_rows = np.asarray(
        [lookup[(record.hdf5_path, record.row)] for record in records],
        dtype=np.int64,
    )
    order = np.argsort(store_rows)
    sorted_rows = store_rows[order]
    if np.unique(sorted_rows).size != sorted_rows.size:
        raise ValueError("Pair manifest reuses an event within a partition")
    t10_fallback_count = 0
    with h5py.File(store_path, "r") as handle:
        if str(handle.attrs["partition"]) != partition:
            raise ValueError(f"Event-store partition mismatch: {store_path}")
        waveform_dataset = handle["waveform"]
        energy_dataset = handle["shaped_energy_unit"]
        selection_density = sorted_rows.size / waveform_dataset.shape[0]
        preload_store = selection_density >= 0.20
        waveform_values = np.asarray(waveform_dataset) if preload_store else None
        energy_values = np.asarray(energy_dataset) if preload_store else None
        for start in range(0, sorted_rows.size, FEATURE_CHUNK_SIZE):
            stop = min(start + FEATURE_CHUNK_SIZE, sorted_rows.size)
            rows = sorted_rows[start:stop]
            destinations = order[start:stop]
            chunk_charge, chunk_current, fallback_count = extract_o2_features(
                waveform_values[rows]
                if waveform_values is not None
                else waveform_dataset[rows],
                energy_values[rows]
                if energy_values is not None
                else energy_dataset[rows],
            )
            charge[destinations] = chunk_charge
            current[destinations] = chunk_current
            t10_fallback_count += fallback_count
    return PartitionData(
        charge,
        current,
        labels,
        weights,
        peak_ids,
        t10_fallback_count,
    )


def standardize_features(
    train: PartitionData,
    validation: PartitionData,
) -> dict[str, float]:
    """Standardize each branch using train-only statistics."""
    statistics: dict[str, float] = {}
    for name in ("charge", "current"):
        train_values = getattr(train, name)
        mean = float(np.mean(train_values, dtype=np.float64))
        standard_deviation = float(np.std(train_values, dtype=np.float64))
        if not np.isfinite(standard_deviation) or standard_deviation <= 0.0:
            raise ValueError(f"Invalid training standard deviation for {name}")
        validation_values = getattr(validation, name)
        train_values -= mean
        train_values /= standard_deviation
        validation_values -= mean
        validation_values /= standard_deviation
        statistics[f"{name}_mean"] = mean
        statistics[f"{name}_std"] = standard_deviation
    return statistics


class ConvBranch(nn.Module):
    def __init__(self, channels: list[int], kernels: list[int], embedding_dim: int) -> None:
        super().__init__()
        layers: list[nn.Module] = []
        in_channels = 1
        for out_channels, kernel in zip(channels, kernels):
            layers.extend(
                (
                    nn.Conv1d(
                        in_channels,
                        out_channels,
                        kernel_size=kernel,
                        padding=kernel // 2,
                    ),
                    nn.BatchNorm1d(out_channels),
                    nn.GELU(),
                    nn.MaxPool1d(kernel_size=2),
                )
            )
            in_channels = out_channels
        self.convolution = nn.Sequential(*layers)
        self.embedding = nn.Sequential(
            nn.AdaptiveAvgPool1d(1),
            nn.Flatten(),
            nn.Linear(channels[-1], embedding_dim),
            nn.LayerNorm(embedding_dim),
            nn.GELU(),
        )

    def forward(self, values: Tensor) -> Tensor:
        return self.embedding(self.convolution(values))


class O2LateFusion(nn.Module):
    def __init__(self) -> None:
        super().__init__()
        self.charge_branch = ConvBranch([16, 32, 64], [9, 9, 7], 64)
        self.current_branch = ConvBranch([16, 32, 64], [7, 7, 5], 64)
        self.fusion = nn.Sequential(
            nn.Linear(128, 64),
            nn.LayerNorm(64),
            nn.GELU(),
            nn.Dropout(0.20),
            nn.Linear(64, 1),
        )

    def forward(self, charge: Tensor, current: Tensor) -> Tensor:
        charge_embedding = self.charge_branch(charge.unsqueeze(1))
        current_embedding = self.current_branch(current.unsqueeze(1))
        return self.fusion(torch.cat((charge_embedding, current_embedding), dim=1)).squeeze(1)


def set_seed(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)
    torch.backends.cudnn.deterministic = True
    torch.backends.cudnn.benchmark = False


def metric_summary(
    labels: np.ndarray,
    scores: np.ndarray,
    weights: np.ndarray,
) -> dict[str, float]:
    return {
        "auroc": float(roc_auc_score(labels, scores)),
        "weighted_auroc": float(roc_auc_score(labels, scores, sample_weight=weights)),
        "average_precision": float(average_precision_score(labels, scores)),
        "weighted_average_precision": float(
            average_precision_score(labels, scores, sample_weight=weights)
        ),
    }


def evaluate(
    model: nn.Module,
    loader: DataLoader[tuple[Tensor, ...]],
    device: torch.device,
) -> tuple[float, dict[str, float], np.ndarray, np.ndarray]:
    model.eval()
    losses: list[float] = []
    labels: list[np.ndarray] = []
    scores: list[np.ndarray] = []
    weights: list[np.ndarray] = []
    with torch.no_grad():
        for charge, current, target, sample_weight in loader:
            charge = charge.to(device, non_blocking=True)
            current = current.to(device, non_blocking=True)
            target = target.to(device, non_blocking=True)
            sample_weight = sample_weight.to(device, non_blocking=True)
            logits = model(charge, current)
            batch_loss = nn.functional.binary_cross_entropy_with_logits(
                logits,
                target,
                reduction="none",
            )
            losses.append(float((batch_loss * sample_weight).sum().item()))
            labels.append(target.cpu().numpy())
            scores.append(torch.sigmoid(logits).cpu().numpy())
            weights.append(sample_weight.cpu().numpy())
    label_array = np.concatenate(labels)
    score_array = np.concatenate(scores)
    weight_array = np.concatenate(weights)
    total_weight = float(np.sum(weight_array))
    metrics = metric_summary(label_array, score_array, weight_array)
    return sum(losses) / total_weight, metrics, label_array, score_array


def train_epoch(
    model: nn.Module,
    loader: DataLoader[tuple[Tensor, ...]],
    optimizer: torch.optim.Optimizer,
    device: torch.device,
) -> float:
    model.train()
    weighted_loss_sum = 0.0
    weight_sum = 0.0
    for charge, current, target, sample_weight in loader:
        charge = charge.to(device, non_blocking=True)
        current = current.to(device, non_blocking=True)
        target = target.to(device, non_blocking=True)
        sample_weight = sample_weight.to(device, non_blocking=True)
        optimizer.zero_grad(set_to_none=True)
        logits = model(charge, current)
        losses = nn.functional.binary_cross_entropy_with_logits(
            logits,
            target,
            reduction="none",
        )
        loss = (losses * sample_weight).sum() / sample_weight.sum()
        loss.backward()
        optimizer.step()
        weighted_loss_sum += float((losses * sample_weight).sum().item())
        weight_sum += float(sample_weight.sum().item())
    return weighted_loss_sum / weight_sum


def make_loader(
    data: PartitionData,
    batch_size: int,
    shuffle: bool,
    seed: int,
) -> DataLoader[tuple[Tensor, ...]]:
    tensors = TensorDataset(
        torch.from_numpy(data.charge),
        torch.from_numpy(data.current),
        torch.from_numpy(data.labels),
        torch.from_numpy(data.weights),
    )
    generator = torch.Generator()
    generator.manual_seed(seed)
    return DataLoader(
        tensors,
        batch_size=batch_size,
        shuffle=shuffle,
        generator=generator,
        num_workers=0,
        pin_memory=torch.cuda.is_available(),
        drop_last=False,
    )


def per_peak_metrics(
    labels: np.ndarray,
    scores: np.ndarray,
    weights: np.ndarray,
    peak_ids: np.ndarray,
) -> dict[str, dict[str, float]]:
    result: dict[str, dict[str, float]] = {}
    for peak_id in sorted(set(peak_ids.tolist())):
        mask = peak_ids == peak_id
        result[peak_id] = metric_summary(labels[mask], scores[mask], weights[mask])
        result[peak_id]["event_count"] = int(np.count_nonzero(mask))
        result[peak_id]["positive_count"] = int(np.count_nonzero(labels[mask] == 1))
        result[peak_id]["negative_count"] = int(np.count_nonzero(labels[mask] == 0))
    return result


