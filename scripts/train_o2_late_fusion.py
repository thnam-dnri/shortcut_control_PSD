#!/usr/bin/env python3
"""Train a provisional O2-style charge/current late-fusion classifier.

This trainer consumes the index-only, file-partitioned pair manifests generated by
``build_energy_matched_labels.py``.  It never materializes a second waveform data
set: each event row is read from its source HDF5 file, converted into two physical
representations, and passed to a small two-branch 1-D CNN.

The implementation is deliberately explicit because this repository did not contain
a canonical O2 model definition.  The frozen representation is:

* median baseline from samples 0:1000;
* baseline-subtracted charge, causally averaged over 10 samples;
* charge window sampled from t10 - 250 through t10 + 499 (750 samples), where t10
  is the interpolated 10%-of-pulse crossing of the smoothed charge;
* current = d(charge)/dt using a 4 ns sample period;
* current window from current-peak - 125 through current-peak + 125 (251 samples),
  with the peak searched in samples 1100:1500;
* both branches normalized by the positive frozen ``shaped_energy_unit``.

Only train and validation partitions are loaded.  The test partition is intentionally
left untouched for a later locked evaluation.  Validation AUROC is an internal,
model-selection diagnostic, not an unbiased physics-performance estimate: positive
and negative classes originate from different isotope sources and the exploratory
manifest retains non-PASS QC files.
"""

